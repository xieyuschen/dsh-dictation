import { readFile, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
import { spawnSync } from 'node:child_process';

// This intentionally small linker handles only the checked-in declaration modules
// below. It creates DSH's classic-script factory format, not an ESM browser entry.
const directory = dirname(fileURLToPath(import.meta.url));
const appRequire = createRequire(import.meta.url);
const sources = [
  { label: '@deepseek-ai/dsh-typert-protocol/remote-info', kind: 'helper' },
  { label: '@deepseek-ai/dsh-experimental-api-speech-to-text/remote', kind: 'remote' },
  ...['dictation-capture.js', 'dictation-store.js', 'dictation-queue.js', 'dictation-service.js', 'dictation-ui.js'].map(label => ({ label, kind: 'local' })),
];
const localModules = new Set(sources.filter(source => source.kind === 'local').map(source => `./${source.label}`));
const hash = createHash('sha256');
hash.update('build-client.mjs\0').update(await readFile(fileURLToPath(import.meta.url))).update('\0');
for (const source of sources) {
  source.path = source.kind === 'local' ? join(directory, source.label) : appRequire.resolve(source.label);
  source.original = await readFile(source.path, 'utf8');
  hash.update(source.label).update('\0').update(source.original).update('\0');
}
const buildId = hash.digest('hex');
function link(source) {
  let text = source.original;
  // Imports must be explicit named imports of our local declarations, or the
  // two known public imports in generated speech metadata. Refuse new externals.
  text = text.replace(/^import\s+([\s\S]*?)\s+from\s+(['"])([^'"]+)\2[ \t]*;?[ \t]*(?:\r?\n|$)/gm, (statement, bindings, quote, specifier) => {
    if (source.kind === 'local' && specifier === 'react' && bindings.trim() === 'React') return '';
    const validLocal = source.kind === 'local' && localModules.has(specifier);
    const validRemote = source.kind === 'remote' && ['zod', '@deepseek-ai/dsh-typert-protocol/remote-info'].includes(specifier);
    if (!validLocal && !validRemote) throw new Error(`${source.label}: unexpected import ${specifier}`);
    if (!/^\{[\s\S]*\}$/.test(bindings.trim()) || /\bas\b/.test(bindings)) throw new Error(`${source.label}: linker only supports unaliased named imports`);
    return '';
  });
  if (source.kind === 'remote') {
    if (!/^export default TYPERT_REMOTE\s*;?\s*$/m.test(text)) throw new Error('Generated speech Remote no longer has the expected default export');
    text = text.replace(/^export default TYPERT_REMOTE\s*;?\s*$/m, '');
  }
  text = text.replace(/^export\s+(?=(?:async\s+)?function\b|class\b|const\b|let\b|var\b)/gm, '');
  text = text.replace(/^export\s*\{[^}]*\}\s*;?[ \t]*(?:\r?\n|$)/gm, '');
  if (/^\s*(?:import|export)\b/m.test(text)) throw new Error(`${source.label}: unsupported import/export remains after linking`);
  return `\n// ---- ${source.label} ----\n${text.trim()}\n`;
}
const artifact = `// Generated by build-client.mjs. Do not edit.\n// Includes MIT-licensed DeepSeek helper and speech Remote metadata; see THIRD_PARTY_NOTICES.md.\n// DSH_DICTATION_BUILD:${buildId}\nwindow.__ModuleLoader__.load({\n  id: '@xieyuschen/dsh-dictation',\n  factory: (require) => {\n    'use strict';\n    const React = require('react');\n    const { z } = require('zod');\n    const DSH_DICTATION_BUILD = '${buildId}';\n${sources.map(link).join('\n')}\n    return { inject: ['remote', 'slots', 'configForms'], apply };\n  }\n});\n`;
// Parsing the complete shared factory catches top-level identifier collisions,
// invalid transforms, and accidental leftover imports before publishing bytes.
const syntax = spawnSync(process.execPath, ['--input-type=commonjs', '--check'], { input: artifact, encoding: 'utf8' });
if (syntax.error) throw syntax.error;
if (syntax.status !== 0) throw new Error(`Client factory failed syntax/collision check:\n${syntax.stderr || syntax.stdout}`);
const output = join(directory, 'client.js');
// Read existing generated output before replacing it; unchanged inputs retain
// their artifact timestamps and therefore do not invent a new DSH revision.
let previous;
try { previous = await readFile(output, 'utf8'); } catch (error) { if (error.code !== 'ENOENT') throw error; }
if (previous !== artifact) await writeFile(output, artifact, 'utf8');
console.log(`DSH_DICTATION_BUILD:${buildId}`);
console.log(`${previous === artifact ? 'Unchanged' : 'Built'} client.js (${Buffer.byteLength(artifact)} bytes); syntax/collision check passed`);
